# ---------------------------------------------------------------------------
# 헤더 정의 (schema.md 2~4절 필드 순서를 그대로 따른다)
# ---------------------------------------------------------------------------
RAW_HEADERS = [
    "article_id", "title", "source_url", "published_at", "body_text",
    "body_char_count", "content_hash", "collected_at", "status",
]
TRIAGE_HEADERS = [
    "article_id", "doc_type", "topics", "personal_relevance",
    "one_line_summary", "audience_groups",
]
DETAIL_HEADERS = [
    "article_id", "summary_easy", "target", "benefit", "how_to_apply",
    "key_dates", "deadline", "region_scope", "evidence_quotes",
]


def build_raw_row(article: dict, collected_at: str) -> list:
    body = article["body_text"]
    content_hash = hashlib.sha256(body.encode("utf-8")).hexdigest()[:16]
    return [
        article["id"],
        article["title"],
        f"https://www.fsc.go.kr/no010101/{article['id']}",
        article["published_at"],
        body,
        len(body),
        content_hash,
        collected_at,
        "active",
    ]


def build_triage_row(article: dict) -> list:
    return [
        article["id"],
        article["doc_type"],
        join_list(article["topics"]),
        article["personal_relevance"],
        article["one_line_summary"],
        join_list(article["audience_groups"]),
    ]


def build_detail_row(article: dict) -> list:
    return [
        article["id"],
        to_cell(article.get("summary_easy")),
        to_cell(article.get("target")),
        to_cell(article.get("benefit")),
        to_cell(article.get("how_to_apply")),
        join_list(article.get("key_dates")),
        to_cell(article.get("deadline")),
        join_list(article.get("region_scope")),
        join_list(article.get("evidence_quotes")),
    ]


def main():
    spreadsheet = get_spreadsheet()
    collected_at = datetime.now(timezone.utc).isoformat(timespec="seconds")

    raw_ws = get_or_create_worksheet(spreadsheet, "articles_raw", RAW_HEADERS)
    triage_ws = get_or_create_worksheet(spreadsheet, "articles_triage", TRIAGE_HEADERS)
    detail_ws = get_or_create_worksheet(spreadsheet, "articles_detail", DETAIL_HEADERS)

    raw_rows = [build_raw_row(a, collected_at) for a in ARTICLES]
    triage_rows = [build_triage_row(a) for a in ARTICLES]
    detail_rows = [
        build_detail_row(a) for a in ARTICLES
        if a["personal_relevance"] in ("direct", "indirect")
    ]

    # 기존 2행 이하 데이터를 지우고 새로 채운다 (헤더인 1행은 유지).
    for ws, rows in [
        (raw_ws, raw_rows),
        (triage_ws, triage_rows),
        (detail_ws, detail_rows),
    ]:
        ws.resize(rows=1)
        ws.resize(rows=max(len(rows) + 1, 2))
        if rows:
            ws.update(range_name="A2", values=rows)

    print(f"articles_raw:    {len(raw_rows)}건")
    print(f"articles_triage: {len(triage_rows)}건")
    print(f"articles_detail: {len(detail_rows)}건 "
          f"(direct {sum(1 for a in ARTICLES if a['personal_relevance']=='direct')}"
          f" + indirect {sum(1 for a in ARTICLES if a['personal_relevance']=='indirect')})")


if __name__ == "__main__":
    main()
